#   2. l-formal g2에서 .row.full의 margin-left는 0으로 지웠지만
#      .row:not(.full) > .body의 padding-left를 지우는 걸 빠뜨려, 주석열이 있는
#      절의 본문만 3.4mm 밀린 채 육안 검토를 통과했다.
