E5_BLOCK = False

PT_PER_MM = 72 / 25.4
# 글리프 바운딩 박스는 활자 크기보다 조금 크게 잡힌다. 그 여유만 허용한다.
BOX_TOL_MM = 0.6
# 쪽번호는 판면 밖(하단 여백 안)에 정상적으로 놓이므로 집계에서 뺀다.
PNUM_MAX_W_MM = 20.0


def _check_page_box(pdf, rel, ax):
    """렌더된 PDF의 콘텐츠가 판면(--mt/--mb/--ml/--mr) 안에 있는지 쪽마다 잰다."""
    if not all(ax.get(k) for k in ("mt", "mb", "ml", "mr")):
        return
    try:
        import pymupdf
    except ImportError:
        add("INFO", "E7", f"{rel}: pymupdf가 없어 판면 좌표 검사를 건너뛴다",
            "    pip install pymupdf — 하단 여백 침범은 육안 검토로는 잡히지 않는다")
        return

    top, bottom = ax["mt"], 297.0 - ax["mb"]
    left, right = ax["ml"], 210.0 - ax["mr"]
    doc = pymupdf.open(pdf)
    total = doc.page_count
    bad, worst = [], None
    for i, page in enumerate(doc, start=1):
        x0 = y0 = float("inf")
        x1 = y1 = float("-inf")
        for b in page.get_text("dict")["blocks"]:
            bx0, by0, bx1, by1 = (v / PT_PER_MM for v in b["bbox"])
            if bx1 - bx0 < 1 or by1 - by0 < 1:
                continue
            if by0 > bottom - 4 and (bx1 - bx0) < PNUM_MAX_W_MM:
                continue  # 쪽번호
            x0, y0 = min(x0, bx0), min(y0, by0)
            x1, y1 = max(x1, bx1), max(y1, by1)
        if x0 == float("inf"):
            continue  # 빈 쪽
        why = []
        # 하단은 표지·목차를 포함해 전 쪽에서 본다. 이 선이 검사의 목적이다.
        if y1 > bottom + BOX_TOL_MM:
            why.append(f"하단 {y1 - bottom:+.1f}mm")
        # 앞장(표지·간지)은 판면을 따르지 않는 게 정상이라 상·좌·우를 면제한다.
        if i > 1:
            if y0 < top - BOX_TOL_MM:
                why.append(f"상단 {top - y0:+.1f}mm")
            if x0 < left - BOX_TOL_MM:
                why.append(f"좌측 {left - x0:+.1f}mm")
            if x1 > right + BOX_TOL_MM:
                why.append(f"우측 {x1 - right:+.1f}mm")
        if why:
            bad.append(f"{i}쪽: {', '.join(why)}")
        room = bottom - y1
        worst = room if worst is None else min(worst, room)
    doc.close()
    if bad:
        add("BLOCK", "E7", f"{rel}: 판면 위반 {len(bad)}쪽 / 전체 {total}쪽",
            "\n".join("    " + b for b in bad[:6])
            + "\n    쪽을 나누거나 표 옆 서술을 줄일 것 — 표 자체를 줄이는 게 아니다")
    elif worst is not None:
        add("INFO", "E7", f"{rel}: 판면 준수 — 하단 여유 최소 {worst:.1f}mm")


def check_report_artifacts():
    # check_hygiene이 이미 git 추적 파일만 보는 것과 같은 이유다. 이 검사에만 그
    # 기준이 적용되지 않아, .gitignore로 막아둔 로컬 PDF(기획 원본·외부에서 받은
    # 자료 등 커밋 대상이 아닌 것)까지 "편집 가능한 원본이 없다"로 잡혔다.
    # 저장소가 의도적으로 추적에서 뺀 파일을 검사 대상으로 삼는 것은 오탐이다.
    tracked = tracked_set()
    pdfs = [p for p in walk((".pdf",))
            if tracked is None or os.path.relpath(p, ROOT).replace(os.sep, "/") in tracked]
    if not pdfs:
        return
    tok = _css_tokens()
    for pdf in pdfs:
        rel = os.path.relpath(pdf, ROOT)
        md = _md_of(pdf)
        html = os.path.splitext(pdf)[0] + ".html"
        stem = unicodedata.normalize("NFC", os.path.basename(os.path.splitext(pdf)[0]))
        if not os.path.isfile(html):
            html = next((p for p in walk((".html",))
                         if unicodedata.normalize("NFC",
                            os.path.basename(os.path.splitext(p)[0])) == stem), None)

        axis = None
        if html and os.path.isfile(html):
            htxt = open(html, encoding="utf-8", errors="ignore").read()
            axis = _body_axis(htxt)

            # E5 비대칭 2단 축인데 report.css의 .row/.aside 구조를 한 번도 안 씀.
            # 표지(.cover-head/.cover-meta)는 애초에 이 클래스를 쓰지 않으므로 따로 뺄
            # 필요가 없다 — 문서 전체에 없다는 것 자체가 본문에서 안 썼다는 뜻이다.
            # l-formal도 같은 구조를 쓴다. 주석열 위치만 반대(좌측)라 검사는 동일하다.
            if axis in ("l-modern", "l-formal"):
                has_row = re.search(r'class=["\'][^"\']*\brow\b', htxt)
                has_aside = re.search(r'class=["\'][^"\']*\baside\b', htxt)
                if not (has_row or has_aside):
                    add("BLOCK" if E5_BLOCK else "WARN", "E5",
                        f"{rel}: {axis} 조판인데 .row/.aside를 쓰지 않음 — "
                        "report.css의 비대칭 2단 구조가 무시됨",
                        "    본문을 --body-w로 좁히고 캡션·측정조건을 --aside-w 열로 보낼 것"
                        " (report-style.md §수치·증거 표기)")

            # E6 인라인 style 금지. 조판 값의 단일 원본은 report.css다 — HTML에
            # style="..."이 하나라도 있으면 그 값은 CSS 밖에서 정해진 것이고, 축을
            # 바꾸거나 색을 바꿔도 따라오지 않는다. "이번 한 줄만"을 허용하면 다음
            # 사람이 또 예외를 만들기 때문에 예외를 두지 않는다.
            inline = re.findall(r'style=["\'][^"\']+["\']', htxt)
            if inline:
                hrel = os.path.relpath(html, ROOT)
                add("BLOCK", "E6",
                    f"{hrel}: 인라인 style {len(inline)}건 — 조판 값이 report.css 밖에 있다",
                    "\n".join("    " + s[:70] for s in inline[:4])
                    + "\n    report.css에 클래스를 만들고 거기서만 값을 정할 것")

        # E1 편집 가능한 원본이 없다. PDF만 남으면 문구 하나 고치는 데 전체 재생성이 필요하다
        if not md:
            add("BLOCK", "E1", f"{rel}: PDF exists but no matching .md — no editable source",
                "    Markdown이 단일 사실 원본이다. PDF는 파생물로만 존재할 것")
            continue
        # E2 조판 미리보기가 없다. 요청 여부와 무관하게 항상 있어야 한다
        if not html:
            add("BLOCK", "E2", f"{rel}: PDF exists but no matching .html preview",
                "    HTML은 조판을 확인하는 가장 싼 수단이다. 중간 산출물이라고 숨기지 말 것")

        # E7 판면 준수를 렌더된 PDF에서 쪽 단위로 실측한다.
        #
        # CSS는 하단 여백을 지켜 주지 못한다. 쪽 높이를 고정하고 넘침을 감추면 조판이
        # 깨진 사실만 사라진다. 육안 검토도 못 잡는다 — 실제로 쪽이 넘쳐 다음 쪽으로
        # 밀려난 이미지가 그 쪽의 불투명한 배경 밑에 깔려, 렌더 PNG를 전부 넘겨봐도
        # 보이지 않은 적이 있다(캡션만 앞 쪽에 남아 캡션·이미지가 갈라진 상태였다).
        # 좌표로만 잡힌다. 그래서 이 검사가 BLOCK이다.
        #
        # 아래 D7 축(텍스트 추출)보다 먼저 둔다. 좌표는 텍스트 레이어와 무관하므로
        # 추출이 안 되는 PDF에서도 판면은 여전히 잴 수 있다.
        ax = tok.get("axis", {}).get(axis or "l-modern", {})
        _check_page_box(pdf, rel, ax)

        mtxt = open(md, encoding="utf-8", errors="ignore").read()
        ptxt = _pdf_text(pdf)
        if not ptxt.strip():
            add("WARN", "D7", f"{rel}: no extractable text — scanned or image-only PDF")
            continue

        # E3 Markdown과 PDF를 따로 쓰는 실패 모드를 직접 잡는다.
        #    쪽 번호·러닝 헤더·캡션 번호는 조판 산물이므로 비교에서 뺀다.
        flat = re.sub(r"\s+", "", ptxt)
        heads = [re.sub(r"\s+", "", h) for h in
                 re.findall(r"^#{1,3}\s+(.+?)\s*$", mtxt, re.M)]
        heads = [h for h in heads if len(h) >= 3]
        miss = [h for h in heads if h not in flat]
        if heads and len(miss) / len(heads) > 0.2:
            add("BLOCK", "E3",
                f"{rel}: {len(miss)}/{len(heads)} headings missing from PDF — md and pdf diverged",
                "\n".join("    " + h for h in miss[:5])
                + "\n    Markdown과 PDF를 서로 독립된 문서로 쓰지 말 것")
        nums = set(re.findall(r"\d+\.\d+", mtxt))
        nmiss = [n for n in sorted(nums) if n.replace(".", "") not in flat.replace(".", "")]
        if nums and len(nmiss) / len(nums) > 0.3:
            add("BLOCK", "E3",
                f"{rel}: {len(nmiss)}/{len(nums)} decimal figures missing from PDF",
                "    " + " · ".join(nmiss[:6]))

        # E4 원본이 더 새롭다. 승인 후 고친 Markdown이 PDF에 반영되지 않았다
        if os.path.getmtime(md) > os.path.getmtime(pdf) + 1:
            add("WARN", "E4", f"{rel}: .md is newer than the PDF — re-render needed",
                "    mode: render-only 로 그 Markdown만 읽어 다시 만들 것")

        # D7 PDF 본문에도 문체 축을 적용한다
        check_overuse(rel + " (pdf)", ptxt, axis="D7")
        cv = _sentence_cv(ptxt)
        if cv is not None and cv < 0.45:
            add("WARN", "D7", f"{rel} (pdf): sentence-length CV {cv:.2f} (target 0.45+)")
        ac = _acronyms(ptxt)
        if ac:
            add("WARN", "D7", f"{rel} (pdf): {len(ac)} acronyms spelled out",
                "\n".join("    " + a for a in ac[:4]))

        # D8 조판이 report.css를 따르는지 대조한다
        info = sh(f"pdfinfo '{pdf}'")
        m = re.search(r"Page size:\s*([\d.]+) x ([\d.]+)", info)
        want = PAGE_PT.get(tok.get("size", "A4"))
        if m and want:
            w, h = float(m.group(1)), float(m.group(2))
            if abs(w - want[0]) > 3 or abs(h - want[1]) > 3:
                add("WARN", "D8",
                    f"{rel}: page {w:.0f}x{h:.0f}pt, expected {tok.get('size','A4')} "
                    f"{want[0]:.0f}x{want[1]:.0f}pt")
        fonts = sh(f"pdffonts '{pdf}'")
        rows = [l for l in fonts.splitlines()[2:] if l.strip()]
        if rows and any(re.split(r"\s+", l.strip())[-5:][0].lower() == "no" for l in rows):
            add("WARN", "D8", f"{rel}: some fonts are not embedded — 한글이 깨질 수 있다")
        # 줄 길이 상한은 축마다 다르다. l-formal은 주석열 없는 절(.row.full)이
        # 판면 전폭을 정상적으로 쓰고 표·코드 블록도 전폭이라, classic·modern의
        # 55자를 그대로 걸면 정상 조판에서 오탐이 난다. 축의 --body-w에서 상한을
        # 계산한다 — 한글 본문은 글자 하나가 대략 활자 크기만큼 폭을 먹으므로
        # 폭(mm) / 2.4mm 에 표·전폭 행의 여유 15%를 얹는다.
        lines = [l.rstrip() for l in _pdf_text(pdf, layout=True).splitlines() if l.strip()]
        bw = ax.get("body_w") or tok.get("body_w") or 114.0
        cap = 55 if axis in (None, "l-classic", "l-modern") else round(bw / 2.4 * 1.15)
        if lines:
            avg = sum(len(l.strip()) for l in lines) / len(lines)
            if avg > cap:
                add("WARN", "D8",
                    f"{rel}: avg line {avg:.0f} chars (max {cap}) — column too wide, "
                    f"report.css --body-w is {bw}mm")


# ═══ 12.5. 줄바꿈 단위 ═══════════════════════════════════════════════════
# 자동 줄바꿈은 report.css의 keep-all이 어절 단위로 강제하고 E9가 그 값을 지킨다.
# 손으로 넣은 줄바꿈은 CSS가 닿지 않는다 — 슬라이드 제목처럼 줄 길이를 맞추려고
# 끊는 자리가 그렇다. 그쪽을 여기서 본다.
#
# **이 검사는 어절 경계를 판정하지 못한다.** 「통/째로」가 갈라졌는지는 형태소를
# 분석해야 알 수 있고, 그 판정을 규칙 몇 줄로 흉내내면 정상 문장을 잡는다
# (「할 수」/「있다」의 '수'는 한 글자짜리 정상 어절이다). 그래서 **어절을 시작할 수
# 없는 형태소로 줄이 시작하는 경우**만 센다. 이건 예외가 없다.
# 나머지는 규칙 문서(ppt-style.md·deck-contract.md·report-style.md)와 사람이 본다.
BOUND_MORPHEME = re.compile(
    r"^(습니다|습니까|합니다|입니다|됩니다|했다|한다|된다|됐다|이다|였다|"
    r"에서|에게|한테|께서|으로|부터|까지|로서|로써|지만|면서|이라고|라고|"
    r"하며|이며|처럼|조차|마저)")
# 오탐률을 모르는 상태로 BLOCK을 켜면 정상 산출물이 막힌다. D5·E5와 같은 방식이다.
WRAP_BLOCK = False


def _wrap_breaks(text):
    """줄바꿈 중 어절을 쪼갠 것이 확실한 자리만 돌려준다."""
    bad = []
    parts = re.split(r"<br\s*/?>|\n", str(text))
    for i, seg in enumerate(parts[1:], 1):
        head = seg.lstrip()
        if not head:
            continue
        if BOUND_MORPHEME.match(head):
            tail = parts[i - 1].rstrip()[-12:]
            bad.append(f"…{tail} ⏎ {head[:12]}…")
    return bad


def _deck_texts(deck):
    for sl in deck.get("slides", []):
        for k in ("title", "subtitle", "probe"):
            if sl.get(k):
                yield sl.get("id", "?"), sl[k]
        for b in sl.get("blocks", []):
            for it in b.get("items", []):
                if not isinstance(it, dict):
                    continue
                for k in ("text", "failure_mode"):
                    if it.get(k):
                        yield sl.get("id", "?"), it[k]


def check_wrap_unit():
    """어절 중간에서 끊긴 수동 줄바꿈을 찾는다."""
    for path in _deck_files():
        rel = os.path.relpath(path, ROOT)
        try:
            deck = json.load(open(path, encoding="utf-8"))
        except Exception:
            continue                            # 파싱 실패는 K0이 이미 내므로 건너뛴다
        hits = [f"{sid}: {h}" for sid, txt in _deck_texts(deck) for h in _wrap_breaks(txt)]
        if hits:
            add("BLOCK" if WRAP_BLOCK else "WARN", "K10",
                f"{rel}: {len(hits)} line break(s) split a word",
                "\n".join("    " + x for x in hits[:6])
                + "\n    줄 길이는 문구를 줄여서 맞춘다 — deck-contract.md 규칙 10")

    for rel, path in _deliverables():
        if not rel.endswith((".md", ".html")):
            continue
        try:
            txt = open(path, encoding="utf-8", errors="ignore").read()
        except Exception:
            continue
        # 마크다운의 문단 개행은 렌더링에서 줄바꿈이 아니다. 명시적 <br>만 본다.
        hits = _wrap_breaks(re.sub(r"\n", " ", txt))
        if hits:
            add("BLOCK" if WRAP_BLOCK else "WARN", "E10",
                f"{rel}: {len(hits)} <br> split(s) a word",
                "\n".join("    " + x for x in hits[:6])
                + "\n    제목·표지에서 줄을 맞추려 끊지 않는다 — report-style.md §줄바꿈")


# ═══ 13. 조판 원본 자체의 하드 규칙 ═════════════════════════════════════
# CSS 주석에 "이 값을 쓴다"라고만 적어 두는 방식은, 사람이든 다음 세션의 Claude든
