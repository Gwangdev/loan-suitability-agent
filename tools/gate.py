TOKENS_CSS = os.path.join(os.path.dirname(SELF), "..", "reference", "report.css")


def _css_block(css, scope):
    """한 규칙 블록만 잘라 온다. 닫는 중괄호까지 안 자르면 값이 없는 블록에서
    파일 뒤쪽 다른 축의 값을 주워 온다."""
    i = css.find(scope)
    if i < 0:
        return ""
    end = css.find("}", i)
    return css[i:end if end > 0 else len(css)]


def _css_mm(css, name, scope):
    m = re.search(re.escape("--" + name) + r":\s*([\d.]+)mm", _css_block(css, scope))
    return float(m.group(1)) if m else None


# 조판 축 → report.css의 해당 블록. 축이 늘면 여기만 고친다.
AXIS_SCOPE = {"l-classic": ".l-classic {", "l-modern": ".l-modern {",
              "l-formal": ".l-formal {"}


def _css_tokens():
    """조판 값의 단일 원본을 읽는다. 게이트가 자기 기준을 따로 갖지 않게 한다."""
    try:
        css = open(TOKENS_CSS, encoding="utf-8").read()
    except Exception:
        return {}
    t = {"axis": {}}
    m = re.search(r"@page\s*\{[^}]*size:\s*([A-Za-z0-9]+)", css)
    if m:
        t["size"] = m.group(1).upper()
    m = re.search(r"--body-w:\s*([\d.]+)mm", _css_block(css, ".report {"))
    if m:
        t["body_w"] = float(m.group(1))
    for axis, scope in AXIS_SCOPE.items():
        t["axis"][axis] = {
            "body_w": _css_mm(css, "body-w", scope) or t.get("body_w"),
            "mt": _css_mm(css, "mt", scope), "mb": _css_mm(css, "mb", scope),
            "ml": _css_mm(css, "ml", scope), "mr": _css_mm(css, "mr", scope),
        }
    return t


def _body_axis(htxt):
    """보고서 HTML의 <body class>에서 조판 축 하나를 뽑는다."""
    m = re.search(r"<body[^>]*class=[\"']([^\"']*)[\"']", htxt)
    cls = set(m.group(1).split()) if m else set()
    return next((a for a in AXIS_SCOPE if a in cls), None)


