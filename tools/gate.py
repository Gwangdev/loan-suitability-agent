# 실패했다. Chrome이 만든 PDF의 텍스트 레이어는 원본 DOM 구조(문단인지 표 셀인지
# 목록 항목인지)를 보존하지 않아, 좌표만으로 그 구조를 되짚을 수 없기 때문이다.
#   3. 어절 단위 줄바꿈(word-break)도 같은 성격이다. 지워도 조판은 그대로 나오고,
