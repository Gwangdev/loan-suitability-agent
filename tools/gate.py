def _deck_files():
    for p in walk((".json",)):
        n = os.path.basename(p)
        if n == "deck.json" or n.endswith(".deck.json"):
            yield p


def _deck_items(deck):
    for sl in deck.get("slides", []):
        for b in sl.get("blocks", []):
            for it in b.get("items", []):
                if isinstance(it, dict) and it.get("text"):
                    yield sl, b, it


def check_deck():
    """슬라이드 스펙에서 AI 지문을 구조 통계로 검출한다."""
    for path in _deck_files():
        rel = os.path.relpath(path, ROOT)
        try:
            deck = json.load(open(path, encoding="utf-8"))
        except Exception as e:
            add("BLOCK", "K0", f"{rel}: parse failed: {e}")
            continue
        items = list(_deck_items(deck))
        if not items:
            add("BLOCK", "K0", f"{rel}: no slide items found",
                "    구조: slides[].blocks[].items[].text")
            continue

        # K1 판단 밀도 — 수치 기준이 없으면 교과서 요약이다
        have = [it for _, _, it in items if it.get("threshold") not in (None, "", [])]
        ratio = len(have) / len(items)
        if ratio < MIN_THRESHOLD_RATIO:
            add("BLOCK", "K1", f"{rel}: judgment density {len(have)}/{len(items)} ({ratio:.0%}) "
                f"— floor {MIN_THRESHOLD_RATIO:.0%}",
                "    '검토한다' 대신 '결측 10% 이하면 row 제거'처럼 수치를 박을 것")

        # K2 실패 조건 — 방법을 제시하면 언제 깨지는지 함께 쓴다
        miss = [(sl, b, it) for sl, b, it in items
                if b.get("label") in DECK_JUDGED and not it.get("failure_mode")]
        if miss:
            add("BLOCK", "K2", f"{rel}: {len(miss)} method items without failure_mode",
                "\n".join(f'    {sl.get("id","?")} / {b.get("label")}: "{it["text"][:32]}…"'
                          for sl, b, it in miss[:6])
                + "\n    그 방법이 오히려 해가 되는 조건을 쓸 것. '주의 필요'는 조건이 아니다")

        # K3 사고 유도 질문
        noprobe = [sl for sl in deck.get("slides", [])
                   if sl.get("kind") in DECK_PROBED and not sl.get("probe")]
        if noprobe:
            add("WARN", "K3", f"{rel}: {len(noprobe)} concept/technique slides without probe",
                "    슬라이드가 답하지 않는 질문 1개를 넣을 것")

        # K4 과도한 대칭 — 사람은 장마다 같은 개수로 쓰지 않는다
        counts = [sum(len(b.get("items", [])) for b in sl.get("blocks", []))
                  for sl in deck.get("slides", []) if sl.get("kind") not in ("section", "closing")]
        counts = [c for c in counts if c]
        if len(counts) >= 4:
            sd = st.pstdev(counts)
            if sd < MIN_COUNT_STDEV:
                add("WARN", "K4", f"{rel}: bullet-count stdev {sd:.2f} — too symmetric",
                    f"    분포 {Counter(counts).most_common()}. 정보량이 많은 장은 늘리고 적은 장은 줄일 것")

        # K5 길이 균일성
        lens = [len(it["text"]) for _, _, it in items]
        if len(lens) >= 10:
            sd = st.pstdev(lens)
            if sd < MIN_LEN_STDEV:
                add("WARN", "K5", f"{rel}: item-length stdev {sd:.1f} (mean {st.mean(lens):.0f})",
                    "    짧은 단정과 조건절 붙은 긴 줄을 의도적으로 섞을 것")

        # K6 내용 없는 수식어 · 서술형 종결
        fillers, narr = [], []
        for sl, b, it in items:
            low = it["text"].lower()
            for ph in DECK_FILLER:
                if ph in low:
                    fillers.append((sl.get("id", "?"), ph))
            if DECK_NARRATIVE.search(it["text"]):
                narr.append(sl.get("id", "?"))
        if fillers:
            add("BLOCK", "K6", f"{rel}: {len(fillers)} filler phrases",
                "\n".join(f'    {i}: "{ph}"' for i, ph in fillers[:6])
                + "\n    정보가 없는 수식어. 삭제하거나 수치로 대체")
        if narr:
            add("WARN", "K7", f"{rel}: {len(narr)} narrative endings — deck style is nominal",
                f"    {', '.join(sorted(set(narr))[:6])} — 명사형(~음/~함)으로 통일")

        # K8 도메인 집중 — 사람은 자기 밥벌이 도메인에 쏠린다
        meta = deck.get("meta") or {}
        home = meta.get("home_domain")
        homes = [home] if isinstance(home, str) else list(home or [])
        homes = [h for h in homes if h and h != "generic"]
        # 강의 주제 자체의 어휘는 드리프트 계산에서 뺀다. IT 강의처럼 주제어가
        # 전 슬라이드에 깔리는 경우 그것이 카운트를 포화시켜 검사가 무력해진다.
        subj = meta.get("subject_domain")
        subjects = [subj] if isinstance(subj, str) else list(subj or [])
        subjects = [x for x in subjects if x and x not in homes]
        if homes:
            corpus = []
            for sl in deck.get("slides", []):
                corpus += [sl.get("probe") or "", sl.get("subtitle") or ""]
            for _, _, it in items:
                corpus += [it["text"], it.get("failure_mode") or ""]
                corpus += list(it.get("sub") or [])
            hits = Counter()
            for line in corpus:
                t = line.lower()
                for dom, words in DOMAIN_LEXICON.items():
                    if any(w in t for w in words):
                        hits[dom] += 1
            total = sum(hits.values())
            for x in subjects:
                hits.pop(x, None)
            total = sum(hits.values())
            own = sum(hits[h] for h in homes)
            label = "+".join(homes)
            if subjects:
                label += f" (subject {'+'.join(subjects)} 제외)"
            if total < 4:
                add("WARN", "K8", f"{rel}: almost no domain vocabulary — examples are abstract",
                    f"    {label} 현장 어휘를 최소 4곳에 박을 것")
            elif 1 - (own / total) > MAX_DOMAIN_DRIFT:
                add("WARN", "K8", f"{rel}: home domain({label}) {own}/{total} — drifting",
                    f"    분포 {dict(hits)}. 도메인을 골고루 흩뿌리면 생성물 티가 난다")

        # K9 부제가 제목의 반복 · 과밀
        for sl in deck.get("slides", []):
            t, sub = (sl.get("title") or "").lower(), (sl.get("subtitle") or "").lower()
            if sub and (t in sub or sub in t):
                add("WARN", "K9", f'{rel} {sl.get("id","?")}: subtitle echoes title',
                    "    부제는 주장을 담을 것. 제목의 부연이 아니다")
            n = sum(len(b.get("items", [])) + sum(len(i.get("sub") or [])
                    for i in b.get("items", []) if isinstance(i, dict))
                    for b in sl.get("blocks", []))
            if n > MAX_LINES_PER_SLIDE:
                add("BLOCK", "K9", f'{rel} {sl.get("id","?")}: {n} lines (max {MAX_LINES_PER_SLIDE})',
                    "    개념을 쪼개 슬라이드를 분리할 것")


