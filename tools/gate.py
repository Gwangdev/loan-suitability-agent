def _md_of(pdf):
    base = os.path.splitext(pdf)[0]
    for cand in (base + ".md", base + ".MD"):
        if os.path.isfile(cand):
            return cand
    stem = unicodedata.normalize("NFC", os.path.basename(base))
    for p in walk((".md",)):
        if unicodedata.normalize("NFC", os.path.basename(os.path.splitext(p)[0])) == stem:
            return p
    return None


