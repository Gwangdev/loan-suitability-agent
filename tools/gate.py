def check_report_css():
    """report.css의 등록된 선택자·속성이 허용값 그대로인지 본다."""
    try:
        css = open(TOKENS_CSS, encoding="utf-8").read()
    except Exception:
        return
    for selector, prop, allowed, miss, hint in CSS_RULES:
        m = re.search(re.escape(selector) + r"\s*\{[^}]*?"
                      + re.escape(prop) + r":\s*([^;}]+)", css)
        if not m:
            add("BLOCK", "E9",
                f"report.css: `{selector} {{ {prop} }}` 규칙이 없다 — "
                "삭제됐거나 선택자가 바뀌었다",
                "    빠지면 " + miss)
        elif m.group(1).strip() != allowed:
            add("BLOCK", "E9",
                f"report.css: `{selector}` {prop}={m.group(1).strip()!r} "
                f"(허용값 {allowed!r}만 가능)",
                "    " + hint)


